import streamlit as st

st.title("Methodology")
st.markdown("""
### Evidence verification
**V0** discovered · **V1** metadata checked · **V2** source checked · **V3** structured evidence extracted · **V4** synthesized.

### Comparability
**C0** non-comparable · **C1** qualitative · **C2** partially comparable · **C3** strongly comparable · **C4** controlled.

### Evidence maturity
The E0–E8 ladder separates definition/demonstration from reproducible, robust, generalizable, testbed, field, and independently replicated evidence.

### Interpretation rule
Reported superiority is not treated as universal superiority. Quantitative claims retain their operating conditions,
baseline, metric definition, implementation context, and uncertainty wherever available.

### Population boundary
MANET routing is the primary population. VANET, FANET, WSN, DTN/opportunistic, mesh, and related evidence is tagged
as transfer or boundary evidence rather than silently pooled.
""")
